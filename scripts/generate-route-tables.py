#!/usr/bin/env python3
"""Write backend/tests/fixtures/route_tables.json: routes_of over every node.

backend/services/node_route.py ``routes_of`` gives every reader one route
shape: a route-table node's own ``routes``, or specs computed for an older
dual-route or single-route node. frontend/src/lib/directRoute.ts ``routesOf``
must compute the same specs, so this snapshot of the Python side (over the
registry and the inline route-table nodes in route_cases.json) is
deep-equalled by frontend/tests/lib/routeTables.test.ts, and
backend/tests/test_node_route.py checks it is current. It also pins the two
KEY_PROVIDERS and PROVIDER_LABELS tables to each other.

Usage:
  backend/.venv/bin/python scripts/generate-route-tables.py          # rewrite
  backend/.venv/bin/python scripts/generate-route-tables.py --check  # exit 1 if stale
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFINITIONS = ROOT / "backend" / "data" / "node_definitions.json"
CASES = ROOT / "backend" / "tests" / "fixtures" / "route_cases.json"
OUT = ROOT / "backend" / "tests" / "fixtures" / "route_tables.json"


def _node_route():
    """backend/services/node_route.py (stdlib only), loaded without the backend's imports."""
    spec = importlib.util.spec_from_file_location("node_route", ROOT / "backend" / "services" / "node_route.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def _route(route: dict) -> dict:
    """One route as the snapshot keeps it: its fields, with params as keys."""
    shown = {key: route[key] for key in ("id", "provider", "maker", "keys", "plan", "handler", "pricing")
             if key in route}
    shown["paramKeys"] = [param["key"] for param in route.get("params") or []]
    if route.get("rules"):
        shown["rules"] = route["rules"]
    return shown


def _offered(param: dict) -> dict:
    """One param as a route offers it (node_route.route_param_definitions):
    its key, its option values and its range."""
    shown = {"key": param["key"]}
    if isinstance(param.get("options"), list):
        shown["options"] = [option.get("value") if isinstance(option, dict) else option for option in param["options"]]
    for bound in ("min", "max"):
        if bound in param:
            shown[bound] = param[bound]
    return shown


def build() -> str:
    node_route = _node_route()
    definitions = json.loads(DEFINITIONS.read_text())
    definitions.update(json.loads(CASES.read_text())["definitions"])
    table = {
        "about": ("Generated by scripts/generate-route-tables.py (do not edit): node_route.routes_of and "
                  "all_param_definitions over every registry node and route_cases.json's inline route-table "
                  "nodes, with params as their keys; for a route-table node, routeParams is "
                  "route_param_definitions per route (each param's key, option values and range). frontend/tests/lib/routeTables.test.ts deep-equals "
                  "directRoute.ts routesOf / allParamDefinitions against it."),
        "keyProviders": node_route.KEY_PROVIDERS,
        "providerLabels": node_route.PROVIDER_LABELS,
        "nodes": {
            node_id: {
                "routes": [_route(route) for route in node_route.routes_of(definition)],
                "allParamKeys": [param["key"] for param in node_route.all_param_definitions(definition)],
                **({"routeParams": {
                    str(route["id"]): [_offered(param) for param in node_route.route_param_definitions(definition, route["id"])]
                    for route in node_route.routes_of(definition)}} if node_route.has_routes(definition) else {}),
            }
            for node_id, definition in sorted(definitions.items())
        },
    }
    return json.dumps(table, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/generate-route-tables.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
