#!/usr/bin/env python3
"""Write backend/tests/fixtures/not_ready_reasons.json: every not-ready
reason the registry gives, for one node and for several.

node_readiness.instance_missing_reason over every registry node, at its
defaults and on each of its routes and an unknown one, with no key set and
with each route's own keys alone, the Krea plan signed out: each distinct
reason (person_line NOT_READY_PREDICATES filled in) once, with the node it
came from and the line the proposal bar shows for one node.
frontend/tests/lib/idolRound15.test.tsx merges every one of them through
canvasProposals.notReadyShown, for one node and for two,
and backend/tests/test_idol_round15.py checks this file is current and that
every line starts with the node's quoted name (review 14 of PR #203, copy
MEDIUM-1 and LOW-1).

Usage:
  backend/.venv/bin/python scripts/generate-not-ready-reasons.py          # rewrite
  backend/.venv/bin/python scripts/generate-not-ready-reasons.py --check  # exit 1 if stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
DEFINITIONS = BACKEND / "data" / "node_definitions.json"
OUT = BACKEND / "tests" / "fixtures" / "not_ready_reasons.json"


def _keys(value: object) -> list[str]:
    if isinstance(value, str):
        return [value]
    return [str(key) for key in value] if isinstance(value, list) else []


def build() -> str:
    sys.path.insert(0, str(BACKEND))
    from services.node_readiness import instance_missing_reason

    definitions = json.loads(DEFINITIONS.read_text())
    seen: dict[str, dict[str, str]] = {}
    for node_id, definition in sorted(definitions.items()):
        variants: list[dict[str, str]] = [{}]
        if definition.get("routes"):
            variants += [{"_provider": str(route.get("id"))} for route in definition["routes"]]
            variants.append({"_provider": "not-a-route"})
        # No key set, then each route's own keys alone (so the other routes
        # are keyless: "Replicate can take it. Add your Replicate token in
        # Settings.").
        key_sets: list[list[str]] = [[]] + [list(_keys(route.get("keys"))) for route in definition.get("routes") or []]
        name = str(definition.get("displayName") or node_id)
        for params in variants:
            for keys in key_sets:
                reason = instance_missing_reason(definition, params, keys, False, definitions)
                if reason is None or reason.view() is None or reason.one in seen:
                    continue
                seen[reason.one] = {"node": node_id, "name": name, "one": reason.one, "many": reason.many,
                                    "line": reason.line(f"“{name}”")}
    table = {
        "about": ("Generated by scripts/generate-not-ready-reasons.py (do not edit): every distinct "
                  "node_readiness.instance_missing_reason over the registry, with no key set and with each "
                  "route's own keys alone."),
        "reasons": list(seen.values()),
    }
    return json.dumps(table, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/generate-not-ready-reasons.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
