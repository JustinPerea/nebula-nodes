"""Generates the port rules the tab and the server share (PR #199 round 17):
which output types may feed which input types, and the kinds of connection
Save as a project can leave out. One run writes the same bytes to both
sides, so the tab's checks (frontend lib/portCompatibility.ts, lib/keptWires.ts)
and the server's connect route (backend services/port_contracts.py) read one
rule and can't differ:

  backend/data/port_rules.json
  frontend/src/lib/portRules.json

The types are the frontend's PORT_DATA_TYPES (src/constants/ports.ts), in
the order of its PORT_COLORS table (src/lib/portCompatibility.ts). Run from
the repo root after changing a type, the extra compatible pairs or the kinds:

  python3 -I scripts/generate-port-rules.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUTS = (ROOT / "backend/data/port_rules.json", ROOT / "frontend/src/lib/portRules.json")
ANY = "Any"
# Pairs that connect either way round although their types differ.
ALSO_COMPATIBLE = [["Image", "Mask"]]
# Why Save as a project left a connection out (the recover route's
# droppedWires `kind`): it connected a node to itself (loop), the same
# connection was there already (duplicate), a node it connected isn't in the
# copy (missing), a port it connected isn't there (port), the input can't
# take that type (type), or the input has as many as it takes (limit).
DROPPED_CONNECTION_KINDS = ["loop", "duplicate", "missing", "port", "type", "limit"]


def main() -> None:
    ports = (ROOT / "frontend/src/constants/ports.ts").read_text(encoding="utf-8")
    colors = (ROOT / "frontend/src/lib/portCompatibility.ts").read_text(encoding="utf-8")
    declared = re.findall(r"'([A-Za-z0-9]+)'", re.search(
        r"PORT_DATA_TYPES: PortDataType\[\] = \[(.*?)\];", ports, re.S).group(1))
    ordered = re.findall(r"^\s+([A-Za-z0-9]+): '#", re.search(
        r"PORT_COLORS: Record<PortDataType, string> = \{(.*?)\};", colors, re.S).group(1), re.M)
    if sorted(declared) != sorted(ordered) or len(set(declared)) != len(declared):
        sys.exit(f"PORT_DATA_TYPES and PORT_COLORS name different types: {sorted(set(declared) ^ set(ordered))}")
    if ordered[-1] != ANY:
        sys.exit("Any must come last")
    data = {
        "about": "Generated by scripts/generate-port-rules.py; the same bytes on both sides (backend "
                 "data/port_rules.json, frontend src/lib/portRules.json). Do not edit by hand.",
        "types": ordered,
        "any": ANY,
        "alsoCompatible": ALSO_COMPATIBLE,
        "droppedConnectionKinds": DROPPED_CONNECTION_KINDS,
    }
    text = json.dumps(data, ensure_ascii=True) + "\n"
    for path in OUTPUTS:
        path.write_text(text, encoding="utf-8")
    print(f"{len(text)} bytes; {len(ordered)} types")


if __name__ == "__main__":
    main()
